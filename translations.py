def _pick(tup: Tuple[str, ...], lang: str) -> str:
    return tup[_IDX.get(lang, 0)] or tup[0]


def t(key: str, lang: str, **fmt) -> str:
    s = _pick(UI[key], lang)
    return s.format(**fmt) if fmt else s


def emirate_name(jur: str, lang: str) -> str:
    return _pick(EMIRATE_NAMES[jur], lang) if jur in EMIRATE_NAMES else jur


def rule_title(rule_id: str, lang: str) -> str:
    return _pick(RULE_TITLES[rule_id], lang) if rule_id in RULE_TITLES else ""


def check_text(check_id: str, status: str, lang: str, **fmt) -> str:
    """Translated message for a rent/date check, or '' when no template exists."""
    key = f"{check_id}.{status}"
    if key not in CHECK_TEXT:
        return ""
    try:
        return _pick(CHECK_TEXT[key], lang).format(**fmt)
    except (KeyError, IndexError):
        return ""
